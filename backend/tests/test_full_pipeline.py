def test_shadow_rubric_generation():
    """Test shadow rubric generation from Pinecone retrieval"""
    async def run_test():
        engine = EssayEvaluationEngine(db)
        
        question = "Explain the federal structure of Indian governance"
        subject = "political-science"
        
        print(f"\n{'='*70}")
        print(f"SHADOW RUBRIC TEST")
        print(f"{'='*70}")
        print(f"\nQuestion: {question}")
        print(f"Subject: {subject}\n")
        
        result = await engine.create_shadow_rubric(question, subject)
            
        if result.get("status") in ["success", "warning"]:
                concepts = result.get("concepts", [])
                print(f"✓ Shadow Rubric Generated with {len(concepts)} concepts:")
                for i, concept in enumerate(concepts, 1):
                    print(f"  {i}. {concept}")
        else:
                print(f"⚠️ {result.get('status')}: {result.get('message', 'Unknown error')}")
    
    asyncio.run(run_test())


def test_pinecone_vector_search():
    """Test Pinecone vector search integration"""
    async def run_test():
        engine = EssayEvaluationEngine(db)
        
        queries = [
            ("What are fundamental rights?", "political-science"),
            ("Explain monsoon patterns", "geography"),
            ("Rise of nationalism in India", "history"),
        ]
        
        print(f"\n{'='*70}")
        print(f"PINECONE VECTOR SEARCH TEST")
        print(f"{'='*70}\n")
        
        for query, subject in queries:
            print(f"🔍 Query: '{query}'")
            print(f"   Subject: {subject}")
            
            results = await engine._query_pinecone(query, subject, top_k=3)
            
            if results:
                print(f"   ✓ Found {len(results)} results:")
                for i, doc in enumerate(results, 1):
                    topic = doc.get("topic", "N/A")
                    score = doc.get("score", 0)
                    print(f"     {i}. {topic} (score: {score:.3f})")
            else:
                print(f"   ⚠️  No results found (index not yet populated)")
            print()
    
    asyncio.run(run_test())


