def test_full_essay_evaluation_pipeline():
    """Complete essay grading pipeline using Groq"""
    async def run_test():
        engine = EssayEvaluationEngine(db)
        
        essay = """
        The Indian Constitution, adopted on January 26, 1950, is a remarkable document that establishes India as a sovereign democratic republic.
        Drafted by the Constituent Assembly under the chairmanship of Dr. B.R. Ambedkar, the Constitution represents a unique synthesis of democratic ideals and Indian values.
        
        The Constitution guarantees fundamental rights to all citizens, including freedom of speech, religion, and equality before law.
        These rights are protected by an independent judiciary that can strike down any law violating constitutional provisions.
        
        The separation of powers among the executive, legislative, and judicial branches ensures effective checks and balances.
        The President is the head of state while the Prime Minister heads the government, following the Westminster model.
        The bicameral Parliament comprises the Lok Sabha (lower house) and the Rajya Sabha (upper house).
        
        Furthermore, the Constitution accommodates India's diversity through federalism and the recognition of regional languages.
        The judicial review power of the Supreme Court has been instrumental in protecting constitutional values and citizens' rights.
        Therefore, the Indian Constitution stands as one of the longest and most comprehensive written constitutions in the world.
        """
        
        question = "Analyze the salient features and importance of the Indian Constitution in establishing democratic governance"
        subject = "political-science"
        
        print(f"\n{'='*70}")
        print(f"ESSAY EVALUATION TEST (Groq + OpenAI Embeddings)")
        print(f"{'='*70}")
        print(f"\nQuestion: {question}")
        print(f"Subject: {subject}")
        print(f"Essay Length: {len(essay)} characters\n")
        
